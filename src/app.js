const express = require('express');
const path = require('path');
const helmet = require('helmet');
const morgan = require('morgan');
const session = require('express-session');
const adminRoutes = require('./routes/admin.routes');
const systemRoutes = require('./routes/system.routes');
const app = express();
const { metricsMiddleware } = require('./observability/metrics');
app.set('view engine', 'ejs');
app.set('views', path.join(__dirname, 'views'));
app.use(helmet({ contentSecurityPolicy: false }));
app.use(morgan('dev'));
app.use(metricsMiddleware);
app.use(express.urlencoded({ extended: true }));
app.use(express.json());
app.use(express.static(path.join(__dirname, 'public')));
app.use(session({ secret: process.env.SESSION_SECRET || 'dev-only-secret', resave: false, saveUninitialized: false, cookie: { httpOnly: true, sameSite: 'lax', secure: process.env.NODE_ENV === 'production' } }));
app.use((req, res, next) => { res.locals.appName = process.env.APP_NAME || 'Supermercado Inteligente'; res.locals.currentPath = req.path; next(); });
app.get('/', (req, res) => res.redirect('/admin/dashboard'));
app.use('/admin', adminRoutes);
app.use('/system', systemRoutes);
app.use((req, res) => res.status(404).render('admin/placeholder', { title: 'Página não encontrada', description: 'O endereço solicitado não existe nesta versão.' }));
module.exports = app;
